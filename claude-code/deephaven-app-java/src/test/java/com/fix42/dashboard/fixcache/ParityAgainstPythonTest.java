package com.fix42.dashboard.fixcache;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.StringJoiner;
import java.util.TreeSet;
import java.util.zip.GZIPInputStream;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * Replays a corpus through this port and asserts every emitted row equals what the python
 * {@code fix42cache} produced for the same input.
 *
 * <p>This is the module's strongest correctness claim, and the reason to trust the port beyond the
 * hand-written rule tests: the two implementations are not merely each "correct according to doc
 * 01", they agree on <em>every column of every row</em> -- state snapshots, execution rows, event
 * rows (including the human-readable {@code Detail} strings), audit rows and error strings.
 *
 * <p>The corpus in {@code src/test/resources/parity/corpus.txt} is deliberately hostile: alongside
 * scenario traffic from {@code :fix-mock-generator} it carries unparseable input, unknown message
 * types and enum codes, values containing {@code =} and {@code |}, duplicate and out-of-range tags,
 * {@code nan}/{@code inf}/underscored/suffixed numbers, and timestamps that probe the difference
 * between {@code strptime} and {@code DateTimeFormatter}.
 *
 * <p>The golden is regenerated by {@code deephaven-app-java/parity/dump_python_rows.py}; see that
 * script for the encoding and for how to refresh it after a contract change.
 */
class ParityAgainstPythonTest {

    private static final String CORPUS = "/parity/corpus.txt";
    private static final String GOLDEN = "/parity/expected.jsonl.gz";

    @Test
    @DisplayName("every row matches the python implementation, column for column")
    void matchesThePythonImplementation() throws IOException {
        List<String> corpus = readCorpus();
        List<String> golden = readGolden();
        assertEquals(corpus.size() + 1, golden.size(),
                "golden must hold one line per message plus the final-chains line; regenerate it with "
                        + "deephaven-app-java/parity/dump_python_rows.py");

        OrderStateMachine machine = new OrderStateMachine(new FakeClock());
        for (int i = 0; i < corpus.size(); i++) {
            Result result = machine.process(corpus.get(i));
            assertEquals(golden.get(i), encode(result), "message #" + i + ": " + corpus.get(i));
        }

        StringJoiner chains = new StringJoiner(",", "{\"finalChains\":[", "]}");
        for (OrderState state : machine.snapshotAll()) {
            chains.add(row(state.toRow()));
        }
        assertEquals(golden.get(golden.size() - 1), chains.toString(), "final chain snapshots");
    }

    @Test
    void theCorpusExercisesEveryMessageTypeAndBothDelimiters() throws IOException {
        List<String> corpus = readCorpus();
        assertTrue(corpus.size() > 200, "corpus shrank unexpectedly: " + corpus.size());

        OrderStateMachine machine = new OrderStateMachine(new FakeClock());
        var seenMsgTypes = new TreeSet<String>();
        var seenEventTypes = new TreeSet<String>();
        var seenFillStatuses = new TreeSet<String>();
        int errors = 0;
        for (String raw : corpus) {
            Result result = machine.process(raw);
            if (result.error() != null) {
                errors++;
            }
            if (result.message() != null) {
                seenMsgTypes.add(result.message().msgType());
            }
            result.events().forEach(e -> seenEventTypes.add(e.eventType()));
            result.executions().forEach(e -> seenFillStatuses.add(e.fillStatus()));
        }

        assertTrue(seenMsgTypes.containsAll(OrderStateMachine.HANDLED_MSG_TYPES), seenMsgTypes.toString());
        assertEquals(
                new TreeSet<>(FillStatus.ALL), seenFillStatuses, "every disposition should be exercised");
        assertTrue(seenEventTypes.size() >= 12, "event coverage thin: " + seenEventTypes);
        assertTrue(errors > 0, "the corpus should include input the machine rejects");
    }

    // ------------------------------------------------------------------ the parity encoding

    /**
     * Renders one {@link Result} exactly as {@code dump_python_rows.py} renders it.
     *
     * <p>Keys sorted; an Instant becomes its epoch-nanosecond count and a double its IEEE-754 bit
     * pattern, so neither side's number/timestamp formatting can create a spurious difference.
     */
    private static String encode(Result result) {
        StringBuilder out = new StringBuilder("{");
        out.append("\"error\":").append(jsonString(result.error())).append(',');
        out.append("\"events\":").append(rows(result.events().stream().map(OrderEventRow::toRow).toList()));
        out.append(",\"executions\":")
                .append(rows(result.executions().stream().map(ExecutionRow::toRow).toList()));
        out.append(",\"message\":")
                .append(result.message() == null ? "null" : row(result.message().toRow()));
        out.append(",\"state\":").append(result.state() == null ? "null" : row(result.state().toRow()));
        return out.append('}').toString();
    }

    private static String rows(List<Map<String, Object>> list) {
        StringJoiner joiner = new StringJoiner(",", "[", "]");
        list.forEach(r -> joiner.add(row(r)));
        return joiner.toString();
    }

    private static String row(Map<String, Object> mapping) {
        StringJoiner joiner = new StringJoiner(",", "{", "}");
        for (String key : new TreeSet<>(mapping.keySet())) {
            joiner.add(jsonString(key) + ":" + value(mapping.get(key)));
        }
        return joiner.toString();
    }

    private static String value(Object v) {
        if (v == null) {
            return "null";
        }
        if (v instanceof String s) {
            return jsonString(s);
        }
        if (v instanceof Boolean b) {
            return b ? "true" : "false";
        }
        if (v instanceof Instant i) {
            return Long.toString(i.getEpochSecond() * 1_000_000_000L + i.getNano());
        }
        if (v instanceof Double d) {
            return Long.toString(Double.doubleToLongBits(d));
        }
        if (v instanceof Long l) {
            return l.toString();
        }
        throw new IllegalStateException("unhandled parity value type: " + v.getClass());
    }

    /** python's {@code json.dumps} escaping for the characters this corpus can produce. */
    private static String jsonString(String s) {
        if (s == null) {
            return "null";
        }
        StringBuilder out = new StringBuilder(s.length() + 2).append('"');
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                case '\b' -> out.append("\\b");
                case '\f' -> out.append("\\f");
                default -> {
                    if (c < 0x20) {
                        out.append(String.format(Locale.ROOT, "\\u%04x", (int) c));
                    } else {
                        out.append(c);
                    }
                }
            }
        }
        return out.append('"').toString();
    }

    // ------------------------------------------------------------------ resources

    private static List<String> readCorpus() throws IOException {
        List<String> lines = new ArrayList<>();
        try (InputStream in = open(CORPUS);
                BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            String line;
            while ((line = reader.readLine()) != null) {
                if (!line.isEmpty()) {
                    lines.add(line);
                }
            }
        }
        return lines;
    }

    private static List<String> readGolden() throws IOException {
        List<String> lines = new ArrayList<>();
        try (InputStream in = open(GOLDEN);
                BufferedReader reader =
                        new BufferedReader(new InputStreamReader(new GZIPInputStream(in), StandardCharsets.UTF_8))) {
            String line;
            while ((line = reader.readLine()) != null) {
                lines.add(line);
            }
        }
        return lines;
    }

    private static InputStream open(String resource) {
        InputStream in = ParityAgainstPythonTest.class.getResourceAsStream(resource);
        assertNotNull(in, "missing test resource " + resource);
        return in;
    }
}
