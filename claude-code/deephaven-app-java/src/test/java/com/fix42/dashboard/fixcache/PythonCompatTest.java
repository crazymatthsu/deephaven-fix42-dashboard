package com.fix42.dashboard.fixcache;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.time.Instant;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.provider.ValueSource;

/**
 * The python-compatibility shims, pinned against values produced by CPython itself.
 *
 * <p>These helpers exist because the JDK's equivalents differ from python's in ways that would
 * change published column values: {@code String.format("%.6g", ...)} keeps trailing zeros,
 * {@code Double.parseDouble} accepts type suffixes, {@code Long.parseLong} rejects underscores, and
 * {@code DateTimeFormatter} rejects one-digit month/day fields that {@code strptime} accepts. Every
 * expectation below was generated by running the corresponding python expression.
 */
class PythonCompatTest {

    @ParameterizedTest
    @CsvSource({
        "0.0,        0",
        "1.0,        1",
        "1000.0,     1000",
        "100.0,      100",
        "-3.75,      -3.75",
        "185.5,      185.5",
        "185.52,     185.52",
        "185.5225,   185.523",
        "0.0001234,  0.0001234",
        "1234567.0,  1234567",
        "1234567.5,  1.23457e+06",
        "999999.5,   1e+06",
        "1e-07,      1e-07",
        "2.5e-05,    2.5e-05",
        "1e20,       100000000000000000000",
    })
    @DisplayName("_num(value) matches python's str(int(v)) / f'{v:.6g}'")
    void numMatchesPython(double value, String expected) {
        assertEquals(expected, PyNum.num(value));
    }

    @Test
    @DisplayName("str(int(v)) is exact for values beyond long range")
    void numIsExactForHugeIntegralValues() {
        assertEquals("12345678901234567168", PyNum.num(12345678901234567890.0));
    }

    @Test
    @DisplayName("0.1 + 0.2 renders as 0.3 at 6 significant digits")
    void numRoundsToSixSignificantDigits() {
        assertEquals("0.3", PyNum.num(0.1 + 0.2));
    }

    @Test
    @DisplayName("python's int(nan) raises ValueError; int(inf) raises OverflowError")
    void numRaisesOnNonFiniteJustLikePython() {
        PyException nan = assertThrows(PyException.class, () -> PyNum.num(Double.NaN));
        assertEquals("ValueError", nan.pyType());
        assertEquals("cannot convert float NaN to integer", nan.getMessage());

        for (double infinite : new double[] {Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY}) {
            PyException inf = assertThrows(PyException.class, () -> PyNum.num(infinite));
            assertEquals("OverflowError", inf.pyType());
            assertEquals("cannot convert float infinity to integer", inf.getMessage());
        }
    }

    @Test
    void aNonFiniteQuantityFailsTheMessageWithoutThrowingOutOfProcess() {
        OrderStateMachine machine = new OrderStateMachine(new FakeClock());
        Result result = machine.process("35=D|11=NAN|1=A|55=S|54=1|38=nan|40=2|44=1.5|59=0");

        assertEquals("internal error: ValueError: cannot convert float NaN to integer", result.error());
        assertNull(result.state());
        assertNull(result.message());
        // python mutates the chain before raising, and so does this port.
        assertEquals(1, machine.orderCount());
    }

    @ParameterizedTest
    @ValueSource(strings = {"1_0", "  12  ", "+7", "-0", "0", ".5", "5.", "1e3", "nan", "inf", "-inf"})
    @DisplayName("python's float() accepts these")
    void pyFloatAcceptsWhatPythonAccepts(String text) {
        PyFloat.parse(text.strip());
    }

    @ParameterizedTest
    @ValueSource(strings = {"100d", "5f", "0x10", "1,000", "abc", "", "1__0", "--1"})
    @DisplayName("python's float() rejects these, and so must this port")
    void pyFloatRejectsWhatPythonRejects(String text) {
        assertThrows(NumberFormatException.class, () -> PyFloat.parse(text));
    }

    @Test
    void pyFloatValues() {
        assertEquals(10.0, PyFloat.parse("1_0"));
        assertEquals(1000.0, PyFloat.parse("1e3"));
        assertEquals(0.5, PyFloat.parse(".5"));
        assertTrue(Double.isInfinite(PyFloat.parse("-inf")));
        assertTrue(Double.isNaN(PyFloat.parse("nan")));
    }

    @Test
    void pyIntAcceptsUnderscoresAndUnboundedValues() {
        assertEquals(10L, PyInt.parse("1_0").longValueExact());
        assertEquals("12345678901234567890", PyInt.parse("12345678901234567890").toString());
        assertThrows(NumberFormatException.class, () -> PyInt.parse("1e3"));
        assertThrows(NumberFormatException.class, () -> PyInt.parse("1__0"));
    }

    @ParameterizedTest
    @CsvSource({
        "20240115-14:30:00,        2024-01-15T14:30:00Z",
        "20240115-14:30:00.123,    2024-01-15T14:30:00.123Z",
        "20240115-14:30:00.1,      2024-01-15T14:30:00.100Z",
        "20240115-14:30:00.123456, 2024-01-15T14:30:00.123456Z",
        "2024011-14:30:00,         2024-01-01T14:30:00Z",
        "20240229-00:00:00,        2024-02-29T00:00:00Z",
        "99991231-23:59:59.999999, 9999-12-31T23:59:59.999999Z",
    })
    @DisplayName("strptime layouts python accepts")
    void strptimeAccepts(String text, String expected) {
        assertEquals(Instant.parse(expected), FixParser.parseTransactTime(text));
    }

    @ParameterizedTest
    @ValueSource(strings = {
        "20240230-14:30:00",
        "20230229-00:00:00",
        "20240115-14:30:60",
        "20240115-24:00:00",
        "20240115 14:30:00",
        "20240115-14:30:00.1234567",
        "202401151-14:30:00",
        "00000101-00:00:00",
    })
    @DisplayName("layouts python rejects, including proleptic year 0 that java.time would accept")
    void strptimeRejects(String text) {
        assertNull(FixParser.parseTransactTime(text));
    }

    @Test
    void pyReprMatchesPythonQuoting() {
        assertEquals("'V'", PyRepr.of("V"));
        assertEquals("\"it's\"", PyRepr.of("it's"));
        assertEquals("'say \"hi\"'", PyRepr.of("say \"hi\""));
        assertEquals("'a\\\\b'", PyRepr.of("a\\b"));
    }
}
