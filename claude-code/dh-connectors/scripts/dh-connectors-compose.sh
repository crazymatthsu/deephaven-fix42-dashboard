#!/usr/bin/env bash
# dh-connectors-compose.sh -- run the config tree's connector applications with podman compose.
#
# The compose file is GENERATED from config/<env>/<flow>/<app-name>/: the tree is the single
# source of truth, so adding application #51 is `mkdir` + one application.yml — no compose
# editing. One service per app directory; each flow is a compose profile, so a slice of the
# fleet starts with `up <flow>` and nobody starts fifty JVMs by accident.
#
#   scripts/dh-connectors-compose.sh local up cache        # just the cache flow's apps
#   scripts/dh-connectors-compose.sh local up              # every flow in local
#   scripts/dh-connectors-compose.sh local ps
#   scripts/dh-connectors-compose.sh local logs portfolios
#   scripts/dh-connectors-compose.sh local down
#
# Each service runs image localhost/dh-connector-app:local — or localhost/dh-<app>:local when
# apps/<app>/ exists (a custom-code application) — with its two config directories mounted
# read-only. Build the images first: scripts/dh-connectors-compose.sh local build.
#
# The generated services publish no ports (connectors are outbound clients; the actuator
# healthcheck runs inside the container network) and reach their sources and Deephaven on the
# host through host.containers.internal. Override per invocation:
#   AMPS_HOST / DEEPHAVEN_HOST   endpoint the containers dial (default host.containers.internal)
#   KAFKA_HOST / TCP_HOST        the same, for the kafka and raw-socket sources
#   IMAGE_TAG                    image tag (default local)
#   DH_CONNECTOR_MEM             per-container memory limit (default 384m; the JVM sizes
#                                itself from it via container awareness)
#   PODMAN                       container tool (default podman)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"                    # dh-connectors/
GRADLE_ROOT="$(dirname "$ROOT")"                   # the gradle build root
PODMAN="${PODMAN:-podman}"

usage() {
    sed -n '2,27p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 1
}

[ $# -ge 2 ] || usage
ENV_NAME="$1"; shift
CMD="$1"; shift
ENV_DIR="$ROOT/config/$ENV_NAME"
[ -d "$ENV_DIR" ] || { echo "no such environment: $ENV_DIR" >&2; exit 1; }
OUT="$ROOT/build/compose/dh-connectors-$ENV_NAME.yml"
PROJECT="dh-connectors-$ENV_NAME"

# ---- discovery -----------------------------------------------------------------

flows() {
    find "$ENV_DIR" -mindepth 1 -maxdepth 1 -type d ! -name common -exec basename {} \; | sort
}

apps_in() { # flow -> app names
    find "$ENV_DIR/$1" -mindepth 2 -maxdepth 2 -name application.yml \
        -exec dirname {} \; | xargs -n1 basename | sort
}

# ---- generation ----------------------------------------------------------------

generate() {
    mkdir -p "$(dirname "$OUT")"
    {
        echo "# GENERATED by scripts/dh-connectors-compose.sh from config/$ENV_NAME/ — do not edit."
        echo "name: $PROJECT"
        echo
        echo "services:"
        local flow app image
        for flow in $(flows); do
            for app in $(apps_in "$flow"); do
                image="dh-connector-app"
                [ -d "$ROOT/apps/$app" ] && image="dh-$app"
                cat <<SERVICE
  $app:
    image: localhost/$image:\${IMAGE_TAG:-local}
    profiles: ["$flow"]
    environment:
      SPRING_APPLICATION_NAME: $app
      AMPS_HOST: \${AMPS_HOST:-host.containers.internal}
      KAFKA_HOST: \${KAFKA_HOST:-host.containers.internal}
      TCP_HOST: \${TCP_HOST:-host.containers.internal}
      DEEPHAVEN_HOST: \${DEEPHAVEN_HOST:-host.containers.internal}
    volumes:
      - $ENV_DIR/common:/app/config/common:ro
      - $ENV_DIR/$flow/$app:/app/config/instance:ro
    mem_limit: \${DH_CONNECTOR_MEM:-384m}
    restart: "no"
    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://localhost:8080/actuator/health/readiness | grep -q UP"]
      interval: 15s
      timeout: 3s
      retries: 20
      start_period: 30s
SERVICE
            done
        done
    } > "$OUT"
    echo "generated $OUT" >&2
}

compose() { # [profiles...] -- args...
    local profile_args=()
    while [ $# -gt 0 ] && [ "$1" != "--" ]; do
        profile_args+=(--profile "$1"); shift
    done
    shift
    "$PODMAN" compose -f "$OUT" "${profile_args[@]}" "$@"
}

# ---- commands ------------------------------------------------------------------

case "$CMD" in
    gen)
        generate
        ;;
    list)
        for flow in $(flows); do
            for app in $(apps_in "$flow"); do
                image="dh-connector-app"; [ -d "$ROOT/apps/$app" ] && image="dh-$app"
                printf '%s/%s/%s  (localhost/%s)\n' "$ENV_NAME" "$flow" "$app" "$image"
            done
        done
        ;;
    build)
        cd "$GRADLE_ROOT"
        tasks=(":dh-connectors:connector-app:dockerBuildLocal")
        for d in "$ROOT"/apps/*/; do
            [ -f "$d/build.gradle.kts" ] && tasks+=(":dh-connectors:apps:$(basename "$d"):dockerBuildLocal")
        done
        ./gradlew "${tasks[@]}"
        ;;
    up)
        generate
        # No flows named = every flow; each named flow activates its profile.
        if [ $# -eq 0 ]; then set -- $(flows); fi
        compose "$@" -- up -d
        compose "$@" -- ps
        ;;
    down|ps|stop|start|restart|logs|config)
        [ -f "$OUT" ] || generate
        compose $(flows) -- "$CMD" "$@"
        ;;
    *)
        usage
        ;;
esac
